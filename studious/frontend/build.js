// Netlify build step: writes config.js from environment variables (or frontend/.env).
// Only PUBLIC values belong here — nothing in the frontend is secret.
const fs = require('fs');
const path = require('path');

const env = { ...process.env };
const envFile = path.join(__dirname, '.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && env[m[1]] === undefined) env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}

const apiBase = (env.API_BASE_URL || '').trim().replace(/\/+$/, '');
if (!apiBase) {
  console.error('API_BASE_URL is not set. Set it in the Netlify dashboard (Site settings → Environment variables)\n' +
    'e.g. https://studious-api.onrender.com');
  process.exit(1);
}
const cfg = {
  API_BASE_URL: apiBase,
  APP_NAME: env.APP_NAME || 'Studious',
  CURRENCY: env.CURRENCY || 'NGN'
};
fs.writeFileSync(path.join(__dirname, 'config.js'),
  '// Generated by build.js — do not edit.\nwindow.STUDIOUS_CONFIG = ' + JSON.stringify(cfg, null, 2) + ';\n');
console.log('config.js written for API', apiBase);
